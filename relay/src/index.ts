// Jam relay: a Worker that creates rooms and a Durable Object (one per room) that holds the
// authoritative JamRoomState and fans it out over hibernatable WebSockets.
// Never log message contents or secrets: only frame types and counts, if anything.
import { DurableObject } from 'cloudflare:workers'
import {
  JAM_LIMITS,
  type JamCreated,
  type JamRoomState,
  type JamServerMessage
} from '../../src/shared/jam'
import {
  EMPTY_ROOM_MS,
  HELLO_TIMEOUT_MS,
  HOST_GRACE_MS,
  addParticipant,
  applyCommand,
  createRoomState,
  frameBytes,
  generateCode,
  generateParticipantId,
  generateSecret,
  isValidCode,
  parseClientMessage,
  rateCheck,
  removeParticipant,
  safeEqual,
  setCapabilities
} from './room'
import { handleArt } from './art'

export { ArtStore } from './art'

// `Env` (with the JAM_ROOM binding) is generated by `wrangler types` into
// worker-configuration.d.ts.

/** What the Durable Object persists (one KV key). */
interface RoomRecord {
  state: JamRoomState
  hostSecret: string
  hostId: string
  /** Set while no host socket is connected (also at creation, before the host joins). */
  hostAwaySince: number | null
  /** Set while no socket at all is connected. */
  emptySince: number | null
}

/** Per-socket data that survives hibernation (serializeAttachment, max 16 KiB). */
interface SocketData {
  /** The ?secret= matched, so this socket may become the host. */
  host: boolean
  connectedAt: number
  /** Participant id once `hello` arrived. */
  pid?: string
  /** Timestamps of recent frames, for the per-socket rate limit. */
  rate: number[]
}

const ROOM_KEY = 'room'
const CREATE_ATTEMPTS = 8
const ALARM_SLACK_MS = 1000

const CORS: Record<string, string> = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
  'Access-Control-Allow-Headers': 'Content-Type',
  'Access-Control-Max-Age': '86400'
}

function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json; charset=utf-8', ...CORS }
  })
}

// Node's WebSocket client cannot read the HTTP status of a refused upgrade, so WebSocket
// refusals accept the upgrade and then close straight away with an app-level code.
export const CLOSE = {
  notFound: { code: 4404, reason: 'Room not found' },
  full: { code: 4409, reason: 'Room is full' },
  wrongKey: { code: 4403, reason: 'Wrong host key' }
} as const

/** Accepts the upgrade, optionally sends an `error` frame, then closes with `close`. */
function refuseSocket(close: { code: number; reason: string }, message?: string): Response {
  const { 0: client, 1: server } = new WebSocketPair()
  server.accept()
  if (message) server.send(JSON.stringify({ type: 'error', message } satisfies JamServerMessage))
  server.close(close.code, close.reason)
  return new Response(null, { status: 101, webSocket: client })
}

const fullMessage = `This Jam is full (${JAM_LIMITS.participants} people).`

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url)
    const path = url.pathname.replace(/\/+$/, '') || '/'

    if (request.method === 'OPTIONS') return new Response(null, { status: 204, headers: CORS })

    if (path === '/' && request.method === 'GET') {
      return json({ ok: true, service: 'combined-player-jam-relay' })
    }

    // Discord cover art for local files (QoL 4).
    if (path === '/art' || path.startsWith('/art/')) {
      const art = await handleArt(request, env, path)
      if (art) return art
    }

    if (path === '/rooms') {
      if (request.method !== 'POST') return json({ error: 'Use POST.' }, 405)
      for (let i = 0; i < CREATE_ATTEMPTS; i++) {
        const code = generateCode()
        const hostSecret = generateSecret()
        if (await env.JAM_ROOM.getByName(code).create(code, hostSecret)) {
          const body: JamCreated = { code, hostSecret }
          return json(body, 201)
        }
      }
      return json({ error: 'Could not find a free room code. Try again.' }, 503)
    }

    const m = /^\/rooms\/([^/]+)\/ws$/.exec(path)
    if (m) {
      if (request.method !== 'GET') return json({ error: 'Use GET.' }, 405)
      if (request.headers.get('Upgrade')?.toLowerCase() !== 'websocket') {
        return json({ error: 'Expected a WebSocket upgrade.' }, 426)
      }
      let code = ''
      try {
        code = decodeURIComponent(m[1] ?? '').toUpperCase()
      } catch {
        // malformed escape: treated as an unknown room
      }
      if (!isValidCode(code)) return refuseSocket(CLOSE.notFound)
      return env.JAM_ROOM.getByName(code).fetch(request)
    }

    return json({ error: 'Not found.' }, 404)
  }
} satisfies ExportedHandler<Env>

export class JamRoom extends DurableObject<Env> {
  private room: RoomRecord | null

  constructor(ctx: DurableObjectState, env: Env) {
    super(ctx, env)
    // Restores after hibernation or eviction. Synchronous KV is available on SQLite-backed
    // objects, so no blockConcurrencyWhile is needed.
    this.room = (ctx.storage.kv.get(ROOM_KEY) as RoomRecord | undefined) ?? null
  }

  /** RPC from the Worker. False when the code is already taken. */
  async create(code: string, hostSecret: string): Promise<boolean> {
    if (this.room) return false
    const now = Date.now()
    this.room = {
      state: createRoomState(code, now),
      hostSecret,
      hostId: generateParticipantId(),
      hostAwaySince: now,
      emptySince: now
    }
    this.save()
    await this.schedule()
    return true
  }

  async fetch(request: Request): Promise<Response> {
    const room = this.room
    if (!room) return refuseSocket(CLOSE.notFound)
    // A non-empty ?secret= that does not match is refused rather than joined as a guest, so a
    // host with a stale key finds out instead of silently losing control.
    const secret = new URL(request.url).searchParams.get('secret') || null
    if (secret !== null && !safeEqual(secret, room.hostSecret)) return refuseSocket(CLOSE.wrongKey)
    const host = secret !== null
    const full =
      // Hard cap on sockets (including ones that have not said hello yet).
      this.live().length >= JAM_LIMITS.participants * 2 ||
      (!host && room.state.participants.length >= JAM_LIMITS.participants)
    if (full) return refuseSocket(CLOSE.full, fullMessage)

    const { 0: client, 1: server } = new WebSocketPair()
    this.ctx.acceptWebSocket(server)
    const data: SocketData = { host, connectedAt: Date.now(), rate: [] }
    server.serializeAttachment(data)

    if (room.emptySince !== null) {
      room.emptySince = null
      this.save()
    }
    await this.schedule()
    return new Response(null, { status: 101, webSocket: client })
  }

  async webSocketMessage(ws: WebSocket, raw: string | ArrayBuffer): Promise<void> {
    const room = this.room
    if (!room) {
      this.safeClose(ws, CLOSE.notFound.code, CLOSE.notFound.reason)
      return
    }
    const data = ws.deserializeAttachment() as SocketData | null
    if (!data) {
      this.safeClose(ws, 1011, 'Lost connection state.')
      return
    }
    if (frameBytes(raw) > JAM_LIMITS.frameBytes) {
      this.safeClose(ws, 1009, 'Message too big.')
      return
    }
    const now = Date.now()
    const rate = rateCheck(data.rate, now)
    data.rate = rate.log
    ws.serializeAttachment(data)
    if (!rate.allowed) {
      this.send(ws, { type: 'error', message: 'Slow down.' })
      return
    }

    const parsed = parseClientMessage(raw)
    if ('error' in parsed) {
      this.send(ws, { type: 'error', message: parsed.error })
      if (!data.pid) this.safeClose(ws, 1008, 'Say hello first.')
      return
    }
    const msg = parsed.message

    if (!data.pid) {
      if (msg.type !== 'hello') {
        this.send(ws, { type: 'error', message: 'Say hello first.' })
        this.safeClose(ws, 1008, 'Say hello first.')
        return
      }
      const pid = data.host ? room.hostId : generateParticipantId()
      const joined = addParticipant(room.state, {
        id: pid,
        name: msg.name,
        isHost: data.host,
        canPlay: msg.canPlay
      })
      if ('error' in joined) {
        this.send(ws, { type: 'error', message: joined.error })
        this.safeClose(ws, CLOSE.full.code, CLOSE.full.reason)
        return
      }
      if (data.host) {
        // A reconnecting host replaces any older host socket that is still open.
        for (const other of this.live(ws)) {
          const od = other.deserializeAttachment() as SocketData | null
          if (od?.pid === pid) {
            other.serializeAttachment({ ...od, pid: undefined })
            this.safeClose(other, 4001, 'Replaced by a newer connection.')
          }
        }
        room.hostAwaySince = null
      }
      data.pid = pid
      ws.serializeAttachment(data)
      room.state = joined.state
      this.save()
      this.send(ws, { type: 'welcome', you: pid, state: room.state })
      this.broadcast({ type: 'state', state: room.state }, ws)
      await this.schedule()
      return
    }

    switch (msg.type) {
      case 'hello':
        this.send(ws, { type: 'error', message: 'You already said hello.' })
        return
      case 'ping':
        this.send(ws, { type: 'pong', t: msg.t, serverTime: Date.now() })
        return
      case 'capabilities': {
        const next = setCapabilities(room.state, data.pid, msg.canPlay)
        if (next !== room.state) this.commit(next)
        return
      }
      case 'command': {
        const result = applyCommand(room.state, data.pid, msg.command, now)
        if ('error' in result) {
          this.send(ws, { type: 'error', message: result.error })
        } else if ('end' in result) {
          await this.closeRoom('The host ended the Jam.')
        } else if (result.state !== room.state) {
          this.commit(result.state)
        }
        return
      }
    }
  }

  async webSocketClose(ws: WebSocket): Promise<void> {
    await this.gone(ws)
  }

  async webSocketError(ws: WebSocket): Promise<void> {
    await this.gone(ws)
  }

  async alarm(): Promise<void> {
    const room = this.room
    if (!room) return
    // Clocks in the runtime are coarse and alarms can fire a touch early; treat anything due
    // within ALARM_SLACK_MS as due so we never reschedule for the same instant.
    const now = Date.now() + ALARM_SLACK_MS
    for (const ws of this.live()) {
      const d = ws.deserializeAttachment() as SocketData | null
      if (d && !d.pid && now - d.connectedAt >= HELLO_TIMEOUT_MS) {
        this.safeClose(ws, 4408, 'No hello in time.')
      }
    }
    if (room.hostAwaySince !== null && now - room.hostAwaySince >= HOST_GRACE_MS) {
      await this.closeRoom('The host left.')
      return
    }
    if (room.emptySince !== null && now - room.emptySince >= EMPTY_ROOM_MS) {
      await this.closeRoom('The Jam expired.')
      return
    }
    await this.schedule()
  }

  // ---------- helpers ----------

  /** Open sockets, optionally excluding one (e.g. the one that is closing). */
  private live(except?: WebSocket): WebSocket[] {
    return this.ctx.getWebSockets().filter((s) => s !== except && s.readyState === WebSocket.OPEN)
  }

  private async gone(ws: WebSocket): Promise<void> {
    const room = this.room
    if (!room) return
    const data = ws.deserializeAttachment() as SocketData | null
    const rest = this.live(ws)
    const now = Date.now()
    let changed = false
    if (data?.pid) {
      const stillThere = rest.some(
        (s) => (s.deserializeAttachment() as SocketData | null)?.pid === data.pid
      )
      if (!stillThere) {
        if (data.pid === room.hostId) {
          // The host stays listed for the grace period so a reconnect keeps its id and the
          // queue's addedBy values; the alarm closes the room if they do not come back.
          room.hostAwaySince ??= now
          changed = true
        } else {
          const next = removeParticipant(room.state, data.pid)
          if (next !== room.state) {
            room.state = next
            this.broadcast({ type: 'state', state: next }, ws)
            changed = true
          }
        }
      }
    }
    if (rest.length === 0 && room.emptySince === null) {
      room.emptySince = now
      changed = true
    }
    if (changed) this.save()
    this.safeClose(ws, 1000, 'Bye.')
    await this.schedule()
  }

  /** Stores a new state and broadcasts it to everyone. */
  private commit(state: JamRoomState): void {
    if (!this.room) return
    this.room.state = state
    this.save()
    this.broadcast({ type: 'state', state })
  }

  private save(): void {
    if (this.room) this.ctx.storage.kv.put(ROOM_KEY, this.room)
  }

  private async closeRoom(reason: string): Promise<void> {
    this.room = null
    const frame: JamServerMessage = { type: 'closed', reason }
    for (const ws of this.live()) {
      this.send(ws, frame)
      this.safeClose(ws, 1000, reason)
    }
    // deleteAll also removes the alarm on compatibility dates >= 2026-02-24.
    await this.ctx.storage.deleteAll()
  }

  /** Points the single alarm at the earliest pending deadline (or clears it). */
  private async schedule(): Promise<void> {
    const room = this.room
    if (!room) return
    const deadlines: number[] = []
    if (room.hostAwaySince !== null) deadlines.push(room.hostAwaySince + HOST_GRACE_MS)
    if (room.emptySince !== null) deadlines.push(room.emptySince + EMPTY_ROOM_MS)
    for (const ws of this.live()) {
      const d = ws.deserializeAttachment() as SocketData | null
      if (d && !d.pid) deadlines.push(d.connectedAt + HELLO_TIMEOUT_MS)
    }
    const storage = this.ctx.storage
    if (deadlines.length === 0) {
      await storage.deleteAlarm()
      return
    }
    const at = Math.min(...deadlines)
    if ((await storage.getAlarm()) !== at) await storage.setAlarm(at)
  }

  private send(ws: WebSocket, msg: JamServerMessage): void {
    try {
      ws.send(JSON.stringify(msg))
    } catch {
      // Socket already gone; its close handler cleans up.
    }
  }

  private broadcast(msg: JamServerMessage, except?: WebSocket): void {
    const text = JSON.stringify(msg)
    for (const ws of this.live(except)) {
      const d = ws.deserializeAttachment() as SocketData | null
      if (!d?.pid) continue
      try {
        ws.send(text)
      } catch {
        // ignore
      }
    }
  }

  private safeClose(ws: WebSocket, code: number, reason: string): void {
    try {
      ws.close(code, reason)
    } catch {
      // already closed
    }
  }
}
